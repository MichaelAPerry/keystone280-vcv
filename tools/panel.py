#!/usr/bin/env python3
"""Generate Rack SVGs and C++ layout headers from layout/*.yaml.

Install the fonttools, brotli and pyyaml packages, then run
python3 tools/panel.py [slug ...] from the repository root.
"""
import math
import sys
from pathlib import Path

import yaml
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "tools" / "fonts" / "BricolageGrotesque.woff2"

PANEL_H = 128.5
HP_MM = 5.08
BG = "#1b1b1d"
INK = "#eee8da"
ACCENT = "#c9a24a"   # keystone mark
DIAL_R_KNOB = 6.1    # Davies1900h knob radius, mm (36 px at 75 dpi)


class Typesetter:
    def __init__(self, weight=700, width=75):
        font = TTFont(str(FONT))
        self.font = instancer.instantiateVariableFont(font, {"wght": weight, "wdth": width, "opsz": 12})
        self.cmap = self.font.getBestCmap()
        self.glyphs = self.font.getGlyphSet()
        self.hmtx = self.font["hmtx"]
        self.upm = self.font["head"].unitsPerEm
        self.cap = self.font["OS/2"].sCapHeight

    def width(self, text, size, tracking=0.0):
        s = size / self.upm
        return sum(self.hmtx[self.cmap[ord(c)]][0] * s for c in text) + tracking * size * (len(text) - 1)

    def path(self, text, x, y, size, anchor="middle", tracking=0.04):
        """Path data for text whose cap height is centred on y."""
        missing = [c for c in text if ord(c) not in self.cmap]
        if missing:
            raise SystemExit(f"font lacks glyphs {missing!r} in {text!r}")
        s = size / self.upm
        w = self.width(text, size, tracking)
        cx = {"middle": x - w / 2, "start": x, "end": x - w}[anchor]
        base = y + self.cap * s / 2
        pen = SVGPathPen(self.glyphs, ntos=lambda v: f"{v:.3f}".rstrip("0").rstrip("."))
        for c in text:
            g = self.cmap[ord(c)]
            self.glyphs[g].draw(TransformPen(pen, (s, 0, 0, -s, cx, base)))
            cx += self.hmtx[g][0] * s + tracking * size
        return pen.getCommands()


def wave_path(kind, x, y, w=3.6, h=2.0):
    """Small waveform symbol centred on (x, y)."""
    l, r, t, b = x - w / 2, x + w / 2, y - h / 2, y + h / 2
    if kind == "sine":
        pts = [(l + w * i / 24, y - h / 2 * math.sin(2 * math.pi * i / 24)) for i in range(25)]
        return "M" + " L".join(f"{px:.3f},{py:.3f}" for px, py in pts)
    if kind == "tri":
        return f"M{l:.3f},{b:.3f} L{x:.3f},{t:.3f} L{r:.3f},{b:.3f}"
    if kind == "saw":
        return f"M{l:.3f},{b:.3f} L{r:.3f},{t:.3f} L{r:.3f},{b:.3f}"
    if kind == "invsaw":
        return f"M{l:.3f},{b:.3f} L{l:.3f},{t:.3f} L{r:.3f},{b:.3f}"
    if kind == "rect":
        return f"M{l:.3f},{b:.3f} L{l:.3f},{t:.3f} L{x:.3f},{t:.3f} L{x:.3f},{b:.3f} L{r:.3f},{b:.3f}"
    if kind == "invrect":
        return f"M{l:.3f},{t:.3f} L{l:.3f},{b:.3f} L{x:.3f},{b:.3f} L{x:.3f},{t:.3f} L{r:.3f},{t:.3f}"
    raise SystemExit(f"unknown wave {kind}")


def build(layout_path: Path, ts: Typesetter):
    L = yaml.safe_load(layout_path.read_text())
    slug, hp = L["slug"], L["hp"]
    W = hp * HP_MM
    text, inverted, strokes, fills = [], [], [], []

    def label(t, x, y, size, anchor="middle", invert=False):
        paths = inverted if invert else text
        paths.append(ts.path(str(t), x, y, size, anchor))

    # Dark control field, gold rule and a light output bay.
    label(L["title"], W / 2, 7.0, 3.7)
    label(L["subtitle"], W / 2, 12.5, 2.05)
    strokes.append(f'<line x1="3" y1="16" x2="{W - 3}" y2="16" stroke="{ACCENT}" stroke-width="0.4"/>')
    label("KEYSTONE 280", W / 2, 125.0, 2.0)
    x, y, w, h = L["jack_bay"]
    fills.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="2" fill="{INK}"/>')
    fills.append(f'<rect x="1.5" y="{y}" width="{x - 2.5}" height="{h}" rx="2" fill="#2d2d31"/>')
    for item in L.get("labels", []):
        t, x, y, size, *rest = item
        label(t, x, y, size, rest[0] if rest else "middle")
    # Keystone mark beside the brand line
    kx, ky = W / 2 - ts.width("KEYSTONE 280", 2.0, 0.04) / 2 - 2.4, 125.0
    fills.append(f'<path d="M{kx-1.3:.2f},{ky-1.0:.2f} L{kx+1.3:.2f},{ky-1.0:.2f} L{kx+0.8:.2f},{ky+1.0:.2f} '
                 f'L{kx-0.8:.2f},{ky+1.0:.2f} Z" fill="{ACCENT}"/>')

    header = [f"// Generated by tools/panel.py from layout/{layout_path.name}. Do not edit.",
              "#pragma once", "", f"namespace layout_{slug} {{"]

    if "display" in L:
        x, y, w, h = L["display"]
        fills.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="1" fill="#111113" '
                     f'stroke="{ACCENT}" stroke-width="0.3"/>')
        for key, value in zip(("X", "Y", "W", "H"), (x, y, w, h)):
            header.append(f"constexpr float DISPLAY_{key} = {float(value)}f;")

    for p in L.get("params", []):
        pid, x, y = p["id"], p["x"], p["y"]
        header.append(f"constexpr float {pid}_X = {float(x)}f, {pid}_Y = {float(y)}f;")
        if "label" in p:
            offset = {"knob": 10.1, "snap": 13.4, "button": 6.2, "toggle": 6.5, "rocker": 6.5}
            label(p["label"], x, y + p.get("label_dy", -offset[p["widget"]]), 1.85)
        if p["widget"] in ("knob", "snap"):
            d = p["dial"]
            labels = d["labels"]
            angles = d.get("angles")          # optional explicit angle per label (uneven dials)
            a0, a1 = (angles[0], angles[-1]) if angles else (d["start"], d["end"])
            n = len(labels)
            kr = d.get("knob_r", DIAL_R_KNOB)   # smaller knobs: set knob_r (mm) in the dial
            r_tick0, r_tick1 = kr + 0.6, kr + 1.3
            r_lab = d.get("r", kr + 3.3)
            for i, lab in enumerate(labels):
                a = math.radians(angles[i] if angles else a0 + (a1 - a0) * i / (n - 1))
                sx, sy = math.sin(a), -math.cos(a)
                strokes.append(f'<line x1="{x + sx * r_tick0:.3f}" y1="{y + sy * r_tick0:.3f}" '
                               f'x2="{x + sx * r_tick1:.3f}" y2="{y + sy * r_tick1:.3f}" '
                               f'stroke="{INK}" stroke-width="0.3"/>')
                lx, ly = x + sx * r_lab, y + sy * r_lab
                if lab.startswith("wave:"):
                    strokes.append(f'<path d="{wave_path(lab[5:], lx, ly, 2.6, 1.6)}" fill="none" '
                                   f'stroke="{INK}" stroke-width="0.3" stroke-linejoin="round"/>')
                elif lab:                # an empty label leaves just the tick
                    label(lab, lx, ly, 1.75)
            header.append(f"constexpr float {pid}_MIN_DEG = {float(a0)}f, {pid}_MAX_DEG = {float(a1)}f;")
        elif p["widget"] == "toggle":
            label(p["up"], x + 3.6, y - 2.4, 1.6, "start")
            label(p["down"], x + 3.6, y + 2.4, 1.6, "start")
        elif p["widget"] == "rocker":    # horizontal rocker: left/right captions at (+-dx, dy)
            dx, dy = p.get("dx", 12.5), p.get("dy", 0.0)
            label(p["left"], x - dx, y + dy, 1.6)
            label(p["right"], x + dx, y + dy, 1.6)

    for lt in L.get("lights", []):       # LEDs: position only, VCV draws the light
        header.append(f"constexpr float {lt['id']}_X = {float(lt['x'])}f, {lt['id']}_Y = {float(lt['y'])}f;")

    for kind in ("inputs", "outputs"):
        for j in L.get(kind, []):
            jid, x, y = j["id"], j["x"], j["y"]
            header.append(f"constexpr float {jid}_X = {float(x)}f, {jid}_Y = {float(y)}f;")
            label(j["label"], x, y - 6, 1.78, invert=(kind == "outputs"))
    header += ["}", ""]

    svg = [f'<?xml version="1.0" encoding="UTF-8"?>',
           f'<!-- Generated by tools/panel.py from layout/{layout_path.name}. Do not edit. -->',
           f'<svg xmlns="http://www.w3.org/2000/svg" width="{W:.2f}mm" height="{PANEL_H}mm" '
           f'viewBox="0 0 {W:.2f} {PANEL_H}">',
           f'<rect width="{W:.2f}" height="{PANEL_H}" fill="{BG}"/>',
           *fills, *strokes,
           f'<path d="{" ".join(text)}" fill="{INK}"/>',
           f'<path d="{" ".join(inverted)}" fill="{BG}"/>',
           "</svg>", ""]
    (ROOT / "res" / f"{slug}.svg").write_text("\n".join(svg))
    out = ROOT / "src" / "layout" / f"{slug}.hpp"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(header))
    print(f"{slug}: res/{slug}.svg, src/layout/{slug}.hpp")


def main():
    ts = Typesetter()
    wanted = set(sys.argv[1:])
    for f in sorted((ROOT / "layout").glob("*.yaml")):
        if not wanted or f.stem in wanted:
            build(f, ts)


if __name__ == "__main__":
    main()
